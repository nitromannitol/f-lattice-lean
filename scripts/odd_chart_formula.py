"""The translation of the odd alternate outputs in the llCenter chart (task 46).

For an ordinary odd alternate output of odd phase w, the register tile R (llCentered) satisfies R(y) = Q(w)(y - a) + J.y + c on
its sites, with Q(w) = quarter(H(swap w)) + h0, J = (num, -den) of the odd parent of w, and the translation

    a = delta(w) - LL(w),   delta(w) = transverseJet(odd).offset - kernelJet(even).offset   (phase 1; 0 for phase 0),
    LL(w) = lexmin over the offsets of the seven copies (alternateJets and the seventh jet), the llCenter lower-left.

The translation is determined modulo the period lattice of Q(w), generated by U(w) = 2 (D + dq, N + nq) (the doubled kernel of
the mediant of the two parents). This script checks the formula for every odd-phase output of length at most three, with zero
residual, and reports the lattice vectors used.
"""
import alt_plane_check as apc
from alt_jets import alternate_jets, seventh_offset_slope, lexmin
from seventh_jet import parents_of, phase, kernel_jet, transverse_jet
from odd_donor_jet import Q_of

words = apc.parse_log(apc.DATA)
ok_all = True
for e in words:
    w = tuple(e["word"])
    if not apc.ordinary(list(w), "odd") or not e["odd"]:
        continue
    (N, D), (nq, dq) = parents_of(w)
    odd_f, even_f = (N, D), (nq, dq)
    ph = phase(w)
    J = (N, -D) if ph == 1 else (0, 0)
    oT = transverse_jet(odd_f)[0]
    eK = kernel_jet(even_f)[0]
    delta = (oT[0] - eK[0], oT[1] - eK[1]) if ph == 1 else (0, 0)
    offs = [j[0] for j in alternate_jets(w, "odd")] + [seventh_offset_slope(w, "odd")[0]]
    LL = lexmin(offs)
    a = (delta[0] - LL[0], delta[1] - LL[1])
    Q = Q_of(list(w))
    res = None
    ok = True
    for (y, dy) in e["odd"]:
        k = dy - (Q((y[0] - a[0], y[1] - a[1])) + J[0] * y[0] + J[1] * y[1])
        if res is None:
            res = k
        elif k != res:
            ok = False
            break
    ok_all = ok_all and ok
    U = (2 * (D + dq), 2 * (N + nq))
    print(w, "phase", ph, "a =", a, "const", res if ok else None, "fits" if ok else "NO FIT", "lattice U =", U, flush=True)
print("all odd-phase outputs fit the formula:", ok_all)
