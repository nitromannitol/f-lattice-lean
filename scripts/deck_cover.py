"""Task 41 check: deck coverage of the standard tiles, and the constructor's standard tiles against StandardTiles.

Run: python3 deck_cover.py MAXLEN LOG [LOG ...]

For a word w and parity p, the modified deck of f = current(parents_at(w), p) has the lattice generated by v1 (the
kernel: (2d, 2n) for odd f, (d, n) for even f) and v2 = (n - d, n + d) (lattice_gens of alt_checks). A set T of sites
covers the deck (PeriodDeck.Covers) iff T meets every class of Z^2 / L. With D = |det(v1, v2)|, the class of a site s
is the pair (a(s) mod D, b(s) mod D) with a(s) = s1 v2y - s2 v2x and b(s) = v1x s2 - v1y s1; these numerators vanish mod D
exactly on L, so T covers iff the keys of T are all D^2-residues of the lattice image, i.e. iff the number of distinct
keys equals D.

For each word, the constructor's standard tile (log `stdOdd` / `stdEven`) is compared with StandardTiles' tile
(alt_tiles.std_odd / std_even): equal as sets (raw), or equal after normalising the lowest site to the origin, or
different (then the symmetric difference is printed, and coverage of the constructor's tile is decided).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import alt_tiles as at  # noqa: E402
import alt_checks as ac  # noqa: E402
import native_compare as nc  # noqa: E402


def deck_basis(f, parity_odd):
    """(v1, v2) of the modified deck: v1 = (2d, 2n) for the odd tile, (d, n) for the even tile; v2 = (n-d, n+d)."""
    n, d = f
    v2 = (n - d, n + d)
    v1 = (2 * d, 2 * n) if parity_odd else (d, n)
    return v1, v2


def covers(T, basis):
    v1, v2 = basis
    D = abs(v1[0] * v2[1] - v1[1] * v2[0])
    keys = set()
    for (s1, s2) in T:
        a = s1 * v2[1] - s2 * v2[0]
        b = v1[0] * s2 - v1[1] * s1
        keys.add((a % D, b % D))
    return len(keys) == D, len(keys), D


def normalised(T):
    if not T:
        return frozenset()
    low = min(T, key=lambda p: (p[1], p[0]))
    return frozenset((x - low[0], y - low[1]) for (x, y) in T)


def main(argv):
    maxlen = int(argv[0])
    logs = argv[1:]
    tiles, _ = nc.parse_all(logs)
    words = ac.words(maxlen)
    rows = []
    for w in words:
        P = at.parents_at(w)
        for parity in ('odd', 'even'):
            f = at.current(P, parity)
            basis = deck_basis(f, parity == 'odd')
            Ts = frozenset(at.std_odd(w) if parity == 'odd' else at.std_even(w))
            ok_s, nk_s, D = covers(Ts, basis)
            name = 'stdOdd' if parity == 'odd' else 'stdEven'
            if (w, name) in tiles:
                Tc = tiles[(w, name)]
                raw_eq = (Tc == Ts)
                norm_eq = (normalised(Tc) == normalised(Ts))
                ok_c, nk_c, _ = covers(Tc, basis)
                diff_c = len(Tc - Ts)
                diff_s = len(Ts - Tc)
            else:
                raw_eq = norm_eq = None
                ok_c = nk_c = diff_c = diff_s = None
            rows.append((w, parity, f, D, ok_s, nk_s, raw_eq, norm_eq, ok_c, nk_c, diff_c, diff_s, len(Ts)))
    print('words of length <= %d: %d; standard tiles: %d' % (maxlen, len(words), len(rows)))
    print('(word, parity, f, |det|, StandardTiles covers, keys, constructor present, raw equal, normalised equal,')
    print('  constructor covers, constructor keys, |Tc - Ts|, |Ts - Tc|, |Ts|)')
    n_std_cov = sum(1 for r in rows if r[4])
    print('StandardTiles tiles covering their deck: %d of %d' % (n_std_cov, len(rows)))
    present = [r for r in rows if r[6] is not None]
    print('constructor standard tiles present: %d of %d' % (len(present), len(rows)))
    eq_raw = [r for r in present if r[6]]
    eq_norm_only = [r for r in present if (not r[6]) and r[7]]
    neq = [r for r in present if not r[7]]
    print('  equal (raw): %d; equal after normalising: %d; different: %d' % (len(eq_raw), len(eq_norm_only), len(neq)))
    print('  constructor covers, among the equal-raw tiles: %d of %d' % (sum(1 for r in eq_raw if r[8]), len(eq_raw)))
    print('  constructor covers, among the different tiles: %d of %d' % (sum(1 for r in neq if r[8]), len(neq)))
    for r in neq:
        print('  DIFF', r[0] or "''", r[1], 'f', r[2], 'D', r[3], 'Tc covers', r[8], 'keys', r[9],
              '|Tc-Ts|', r[10], '|Ts-Tc|', r[11], '|Ts|', r[12])
    print('  not covering the deck (constructor):', [(r[0] or "''", r[1]) for r in present if not r[8]])
    print('  not covering the deck (StandardTiles):', [(r[0] or "''", r[1]) for r in rows if not r[4]])


if __name__ == '__main__':
    main(sys.argv[1:])
